def seed(generate_embeddings: bool = False) -> None:
    created = 0
    skipped = 0

    for data in BOOKS:
        obj, is_new = Book.objects.get_or_create(
            title=data['title'],
            author=data['author'],
            defaults={
                'description': data['description'],
                'genre': data['genre'],
                'year': data.get('year'),
                'rating': data.get('rating'),
            },
        )
        if is_new:
            created += 1
        else:
            skipped += 1

    logger.info('Seed complete: %d created, %d already existed.', created, skipped)

    if generate_embeddings:
        _generate_embeddings()


def _generate_embeddings() -> None:
    from openai import OpenAI
    from django.conf import settings

    if not settings.OPENAI_API_KEY:
        logger.warning('OPENAI_API_KEY not set — skipping embedding generation.')
        return

    client = OpenAI(api_key=settings.OPENAI_API_KEY)
    books_without_embeddings = Book.objects.filter(embedding__isnull=True)
    total = books_without_embeddings.count()
    logger.info('Generating embeddings for %d books...', total)

    for i, book in enumerate(books_without_embeddings, start=1):
        text = (
            f'Назва: {book.title}. Автор: {book.author}. '
            f'Жанр: {book.genre}. Опис: {book.description}'
        )
        try:
            response = client.embeddings.create(
                model=settings.EMBEDDING_MODEL,
                input=text,
            )
            book.embedding = response.data[0].embedding
            book.save(update_fields=['embedding'])
            logger.info('[%d/%d] Embedded: %s', i, total, book.title)
        except Exception as exc:
            logger.error('Failed to embed "%s": %s', book.title, exc)


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description='Seed books into the database.')
    parser.add_argument(
        '--embeddings', action='store_true',
        help='Generate OpenAI embeddings for all books after seeding.'
    )
    args = parser.parse_args()
    seed(generate_embeddings=args.embeddings)
    logger.info('Done.')
